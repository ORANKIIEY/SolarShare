// Copies the live contract addresses, ABIs and document list from
// Blockchain/deployments/<network>.json into src/lib/contracts.generated.ts,
// so the web app always uses exactly what was deployed.
//
//   npm run sync:contracts              (Base Sepolia)
//   npm run sync:contracts -- localhost
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const network = process.argv[2] ?? "baseSepolia";
const source = resolve(here, `../../Blockchain/deployments/${network}.json`);
const target = resolve(here, "../src/lib/contracts.generated.ts");

const d = JSON.parse(readFileSync(source, "utf8"));
const names = ["SolarShareToken", "MeterOracle", "RevenueDistributor", "ShareSale", "USDC"];

const contracts = Object.fromEntries(
  names.map((n) => {
    const c = d.contracts[n];
    if (!c) throw new Error(`${n} missing from ${source}`);
    return [n, { address: c.address, explorer: c.explorer, abi: c.abi }];
  }),
);

const deployment = {
  network: d.network,
  chainId: d.chainId,
  startBlock: d.startBlock,
  settings: d.settings,
  documents: d.documents,
  usdcIsMock: Boolean(d.contracts.USDC.mock),
  contracts,
};

const out = `// GENERATED by scripts/sync-contracts.mjs from Blockchain/deployments/${network}.json.
// Do not edit by hand: run \`npm run sync:contracts\` after a new deploy.
export const deployment = ${JSON.stringify(deployment)} as const;
`;
writeFileSync(target, out);
console.log(`Wrote ${target} (${network}, chain ${d.chainId})`);
